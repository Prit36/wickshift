// Snap–launch–retry clip: node tools/clip.mjs → captures/clip/*.webm (real mouse and keys).
import { chromium } from '@playwright/test';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { pageUrl } from './url.mjs';

const exe = join(homedir(), 'AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe');
const browser = await chromium.launch({ executablePath: exe });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 768 }, recordVideo: { dir: 'captures/clip', size: { width: 1366, height: 768 } } });
const page = await ctx.newPage();
await page.goto(pageUrl());
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.__wickshift && window.__wickshift.frameCount > 2);
const g = (fn) => page.evaluate(`(() => { const g = window.__wickshift; return (${fn})(g); })()`);
await page.waitForTimeout(600);
const rec = await g((g) => { const r = g.L.recesses.find((x) => x.kind === 'keyWheel').r; return [(r.x + r.w / 2) * g.L.s, (r.y + r.h / 2) * g.L.s]; });
await page.mouse.move(rec[0], rec[1]);
await page.mouse.down();
await page.mouse.move(rec[0] + 30, rec[1] - 60, { steps: 10 });
const s = await g((g) => { const t = g.computeTargets('keyWheel').filter((t) => t.res.ok).pop(); return [g.cam.sx(t.x) * g.L.s, g.cam.sy(t.y) * g.L.s]; });
await page.mouse.move(s[0], s[1], { steps: 25 });
await page.waitForTimeout(200);
await page.mouse.up();
await page.waitForTimeout(700);
const lever = await g((g) => [(g.L.lever.x + g.L.lever.w / 2) * g.L.s, (g.L.lever.y + 40) * g.L.s]);
await page.mouse.move(lever[0], lever[1], { steps: 15 });
await page.mouse.down();
await page.mouse.up();
await page.keyboard.down('Space');
await page.waitForTimeout(3500);
await page.keyboard.up('Space');
await page.waitForTimeout(500);
await page.keyboard.press('KeyR');
await page.waitForTimeout(1200);
const path = await page.video().path();
await ctx.close();
await browser.close();
console.log('clip', path);
